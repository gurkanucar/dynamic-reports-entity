-- Module 'assistant': its own tables only, no foreign keys into other modules.
-- Versions 110.x belong to this module (generated once from the JPA mapping, owned here since).

create table report_suggestion (
        created_at timestamp(6) with time zone not null,
        finished_at timestamp(6) with time zone,
        id bigint generated by default as identity,
        started_at timestamp(6) with time zone,
        error_code varchar(60),
        owner varchar(100) not null,
        model varchar(200),
        error_message varchar(1000),
        request_json varchar(200000) not null,
        result_json varchar(200000),
        status enum ('COMPLETED','FAILED','PROCESSING','QUEUED') not null,
        primary key (id)
    );

create index ix_report_suggestion_owner 
       on report_suggestion (owner, created_at);

create index ix_report_suggestion_created 
       on report_suggestion (created_at);
