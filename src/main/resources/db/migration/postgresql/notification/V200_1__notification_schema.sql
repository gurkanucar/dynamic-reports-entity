-- Module 'notification': its own tables only, no foreign keys into other modules.
-- Versions 200.x belong to this module (generated once from the JPA mapping, owned here since).

create table notification_mail_template (
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) with time zone not null,
        version bigint not null,
        name varchar(100) not null,
        owner varchar(100) not null,
        updated_by varchar(100) not null,
        subject varchar(500) not null,
        description varchar(1000),
        body_html varchar(200000) not null,
        primary key (id),
        constraint uk_mail_template_name unique (name)
    );
