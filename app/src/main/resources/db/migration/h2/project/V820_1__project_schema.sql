-- Module 'project': its own tables only, no foreign keys into other modules.
-- Versions 820.x belong to this module (generated once from the JPA mapping, owned here since).

create table project (
        budget numeric(38,2),
        end_date date,
        start_date date,
        department_id bigint,
        id bigint generated by default as identity,
        code varchar(255) not null unique,
        name varchar(255),
        status varchar(255),
        primary key (id)
    );

create table project_assignment (
        allocation_percent integer,
        assigned_on date,
        id bigint generated by default as identity,
        personnel_id bigint not null,
        project_id bigint not null,
        role varchar(255),
        primary key (id)
    );

create index ix_project_department_id 
       on project (department_id);

create index ix_project_assignment_project_id 
       on project_assignment (project_id);

create index ix_project_assignment_personnel_id 
       on project_assignment (personnel_id);
