-- Module 'training': its own tables only, no foreign keys into other modules.
-- Versions 830.x belong to this module (generated once from the JPA mapping, owned here since).

create table training (
        mandatory boolean,
        validity_months integer,
        id bigint generated by default as identity,
        category varchar(255),
        internal_notes varchar(255),
        name varchar(255) not null,
        primary key (id)
    );

create table training_record (
        completed_on date,
        next_renewal_date date,
        score integer,
        id bigint generated by default as identity,
        personnel_id bigint not null,
        training_id bigint not null,
        status varchar(255),
        primary key (id)
    );

create index ix_training_record_personnel_id 
       on training_record (personnel_id);

create index ix_training_record_training_id 
       on training_record (training_id);

create index ix_training_record_next_renewal_date 
       on training_record (next_renewal_date);
