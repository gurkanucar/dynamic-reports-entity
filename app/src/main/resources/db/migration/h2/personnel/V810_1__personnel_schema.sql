-- Module 'personnel': its own tables only, no foreign keys into other modules.
-- Versions 810.x belong to this module (generated once from the JPA mapping, owned here since).

create table personnel (
        active boolean,
        hire_date date,
        salary numeric(38,2),
        department_id bigint,
        id bigint generated by default as identity,
        manager_id bigint,
        email varchar(255),
        full_name varchar(255) not null,
        national_id varchar(255),
        username varchar(255) unique,
        primary key (id)
    );

create table personnel_profile (
        birth_date date,
        id bigint generated by default as identity,
        personnel_id bigint not null unique,
        blood_type varchar(255),
        city varchar(255),
        emergency_contact varchar(255),
        primary key (id)
    );

create table personnel_skill (
        personnel_id bigint not null,
        skill_id bigint not null,
        primary key (personnel_id, skill_id)
    );

create table skill (
        id bigint generated by default as identity,
        category varchar(255),
        name varchar(255) not null unique,
        primary key (id)
    );

create index ix_personnel_department_id 
       on personnel (department_id);

create index ix_personnel_manager_id 
       on personnel (manager_id);

create index ix_personnel_skill_skill_id 
       on personnel_skill (skill_id);
