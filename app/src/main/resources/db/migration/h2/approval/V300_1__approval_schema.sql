-- Module 'approval': its own tables only, no foreign keys into other modules.
-- Versions 300.x belong to this module (generated once from the JPA mapping, owned here since).

create table approval_group (
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) with time zone not null,
        version bigint not null,
        name varchar(100) not null,
        updated_by varchar(100) not null,
        description varchar(1000),
        primary key (id),
        constraint uk_approval_group_name unique (name)
    );

create table approval_group_member (
        group_id bigint not null,
        username varchar(100) not null,
        email varchar(254)
    );

create table approval_request (
        allow_self_approval boolean not null,
        created_at timestamp(6) with time zone not null,
        decided_at timestamp(6) with time zone,
        due_at timestamp(6) with time zone not null,
        group_id bigint not null,
        id bigint generated by default as identity,
        source_type varchar(40) not null,
        decided_by varchar(100),
        group_name varchar(100) not null,
        on_behalf_of varchar(100) not null,
        requested_by varchar(100) not null,
        source_id varchar(100) not null,
        subject varchar(200) not null,
        link varchar(300),
        title varchar(300) not null,
        comment varchar(1000),
        description varchar(4000),
        status enum ('APPROVED','CANCELLED','PENDING','REJECTED','TIMED_OUT') not null,
        primary key (id),
        constraint uk_approval_request_source unique (source_type, source_id)
    );

create index ix_approval_request_group 
       on approval_request (group_id, status, created_at);

create index ix_approval_request_due 
       on approval_request (status, due_at);

alter table if exists approval_group_member 
       add constraint FK926erommn8dnbi3saf9bplg53 
       foreign key (group_id) 
       references approval_group;
