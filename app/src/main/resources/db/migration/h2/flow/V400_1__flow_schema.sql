-- Module 'flow': its own tables only, no foreign keys into other modules.
-- Versions 400.x belong to this module (generated once from the JPA mapping, owned here since).

create table flow_artifact (
        created_at timestamp(6) with time zone not null,
        deleted_at timestamp(6) with time zone,
        expires_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        run_id bigint not null,
        size_bytes bigint not null,
        step_run_id bigint not null,
        content_type varchar(100) not null,
        file_name varchar(120) not null,
        storage_key varchar(300) not null,
        primary key (id)
    );

create table flow_definition (
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) with time zone not null,
        version bigint not null,
        name varchar(100) not null,
        owner varchar(100) not null,
        updated_by varchar(100) not null,
        description varchar(1000),
        definition_json varchar(200000) not null,
        primary key (id)
    );

create table flow_mail_delivery (
        id bigint generated by default as identity,
        run_id bigint not null,
        sent_at timestamp(6) with time zone not null,
        step_run_id bigint not null,
        subject varchar(500) not null,
        recipients varchar(4000) not null,
        primary key (id),
        constraint uk_mail_delivery_step unique (step_run_id)
    );

create table flow_run (
        cancel_requested boolean not null,
        priority integer not null,
        created_at timestamp(6) with time zone not null,
        finished_at timestamp(6) with time zone,
        flow_id bigint not null,
        id bigint generated by default as identity,
        schedule_id bigint,
        started_at timestamp(6) with time zone,
        error_code varchar(60),
        flow_name varchar(100) not null,
        run_as varchar(100) not null,
        triggered_by varchar(100) not null,
        error_message varchar(1000),
        definition_json varchar(200000) not null,
        trigger_payload_json varchar(300000),
        status enum ('CANCELLED','COMPLETED','FAILED','QUEUED','RUNNING') not null,
        trigger_type enum ('KAFKA','MANUAL','SCHEDULE','WEBHOOK') not null,
        primary key (id)
    );

create table flow_run_event (
        id bigint generated by default as identity,
        occurred_at timestamp(6) with time zone not null,
        run_id bigint not null,
        step_key varchar(40),
        type varchar(40) not null,
        message varchar(1000),
        primary key (id)
    );

create table flow_schedule (
        enabled boolean not null,
        created_at timestamp(6) with time zone not null,
        flow_id bigint not null,
        id bigint generated by default as identity,
        last_fired_at timestamp(6) with time zone,
        last_run_id bigint,
        next_fire_at timestamp(6) with time zone,
        updated_at timestamp(6) with time zone not null,
        version bigint not null,
        time_zone varchar(60) not null,
        created_by varchar(100) not null,
        cron varchar(100) not null,
        last_skip_reason varchar(300),
        primary key (id)
    );

create table flow_step_reference (
        flow_id bigint not null,
        kind varchar(40) not null,
        ref_id varchar(100) not null,
        primary key (flow_id, kind, ref_id)
    );

create table flow_step_run (
        attempt integer not null,
        max_attempts integer not null,
        priority integer not null,
        step_index integer not null,
        timeout_seconds integer not null,
        available_at timestamp(6) with time zone not null,
        finished_at timestamp(6) with time zone,
        id bigint generated by default as identity,
        lease_until timestamp(6) with time zone,
        run_id bigint not null,
        started_at timestamp(6) with time zone,
        outcome varchar(20),
        step_type varchar(30) not null,
        step_key varchar(40) not null,
        error_code varchar(60),
        owner varchar(120),
        error_message varchar(1000),
        output_json varchar(1000000),
        lane enum ('HEAVY','LIGHT') not null,
        status enum ('CANCELLED','COMPLETED','FAILED','READY','RUNNING','WAITING') not null,
        primary key (id)
    );

create table flow_trigger (
        enabled boolean not null,
        created_at timestamp(6) with time zone not null,
        flow_id bigint not null,
        id bigint generated by default as identity,
        last_fired_at timestamp(6) with time zone,
        last_run_id bigint,
        updated_at timestamp(6) with time zone not null,
        version bigint not null,
        webhook_secret varchar(64),
        webhook_token varchar(64),
        created_by varchar(100) not null,
        topic varchar(249),
        filter_json varchar(20000),
        trigger_type enum ('KAFKA','WEBHOOK') not null,
        primary key (id),
        constraint uk_flow_trigger_token unique (webhook_token)
    );

create table flow_trigger_event (
        id bigint generated by default as identity,
        received_at timestamp(6) with time zone not null,
        run_id bigint,
        trigger_id bigint not null,
        event_key varchar(200) not null,
        primary key (id),
        constraint uk_flow_trigger_event unique (trigger_id, event_key)
    );

