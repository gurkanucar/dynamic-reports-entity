-- Module 'survey': its own tables only, no foreign keys into other modules.
-- Versions 500.x belong to this module.

create table survey (
        anonymous boolean not null,
        one_response_per_user boolean not null,
        closes_at timestamp(6) with time zone,
        created_at timestamp(6) with time zone not null,
        published_at timestamp(6) with time zone,
        updated_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        version bigint not null,
        title varchar(200) not null,
        description varchar(2000),
        owner varchar(100) not null,
        updated_by varchar(100) not null,
        status enum ('CLOSED','DRAFT','PUBLISHED') not null,
        definition_json varchar(200000) not null,
        primary key (id)
    );

create table survey_response (
        id bigint generated by default as identity,
        survey_id bigint not null,
        survey_version bigint not null,
        submitted_at timestamp(6) with time zone not null,
        respondent varchar(100),
        respondent_key varchar(64),
        answers_json varchar(100000) not null,
        primary key (id),
        constraint uk_survey_response_respondent unique (survey_id, respondent_key)
    );

create index ix_survey_owner on survey (owner);
create index ix_survey_status on survey (status);
create index ix_survey_response_survey on survey_response (survey_id, submitted_at);
