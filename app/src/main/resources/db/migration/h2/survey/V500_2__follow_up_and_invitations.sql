-- Follow-up of responses (status, priority, date, assignee, extra fields, notes), result visibility and the links a
-- waiting flow step sends (invitations).
alter table survey add column settings_json varchar(20000);

alter table survey_response add column follow_status enum ('IN_PROGRESS','NEW','RESOLVED','UNRESOLVED') default 'NEW' not null;
alter table survey_response add column priority enum ('HIGH','LOW','NORMAL');
alter table survey_response add column priority_rank integer;
alter table survey_response add column follow_up_at date;
alter table survey_response add column assignee varchar(100);
alter table survey_response add column tracking_json varchar(20000);
alter table survey_response add column source_type varchar(40);
alter table survey_response add column source_id varchar(100);
alter table survey_response add column updated_at timestamp(6) with time zone;
alter table survey_response add column updated_by varchar(100);
create index ix_survey_response_follow on survey_response (survey_id, follow_status);

create table survey_response_note (
        id bigint generated by default as identity,
        survey_id bigint not null,
        response_id bigint not null,
        author varchar(100) not null,
        text varchar(2000) not null,
        created_at timestamp(6) with time zone not null,
        primary key (id)
    );
create index ix_survey_note_response on survey_response_note (response_id);

create table survey_invitation (
        token varchar(64) not null,
        survey_id bigint not null,
        source_type varchar(40) not null,
        source_id varchar(100) not null,
        created_at timestamp(6) with time zone not null,
        expires_at timestamp(6) with time zone not null,
        response_id bigint,
        revoked boolean not null,
        primary key (token),
        constraint uk_survey_invitation_source unique (source_type, source_id)
    );
