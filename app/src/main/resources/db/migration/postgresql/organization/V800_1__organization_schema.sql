-- Module 'organization': its own tables only, no foreign keys into other modules.
-- Versions 800.x belong to this module (generated once from the JPA mapping, owned here since).

create table department (
        id bigint generated by default as identity,
        manager_id bigint,
        parent_id bigint,
        cost_center varchar(255),
        name varchar(255) not null,
        primary key (id)
    );

create index ix_department_parent_id 
       on department (parent_id);

create index ix_department_manager_id 
       on department (manager_id);
